  /**
   * 把英文释义合并进词库。
   * 只填补「cn 字段无英文」且「本表有该词」的条目——已有英文释义的不覆盖。
   */
  function apply(records) {
    var filled = 0, skipped = 0;
    records.forEach(function (w) {
      if (!w || !w.w) return;
      var d = DEFS[w.w];
      if (!d) return;
      var cn = String(w.cn || '');
      // 已有英文说明就不覆盖，避免丢掉更详细的原释义
      if (/[a-zA-Z]{2,}/.test(cn)) { skipped++; return; }
      w.cn = cn ? (cn + ' / ' + d[1]) : d[1];
      w.en = d[0];
      filled++;
    });
    return { filled: filled, skipped: skipped, total: Object.keys(DEFS).length };
  }

